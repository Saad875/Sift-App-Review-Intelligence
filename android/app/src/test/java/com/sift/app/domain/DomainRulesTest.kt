class CompetitorRulesTest {
    @Test
    fun `canAdd enforces limit, length and duplicates`() {
        assertTrue(CompetitorRules.canAdd(listOf("A"), "B"))
        assertFalse(CompetitorRules.canAdd(listOf("A"), " a "))
        assertFalse(CompetitorRules.canAdd(listOf("A", "B", "C"), "D"))
        assertFalse(CompetitorRules.canAdd(emptyList(), "   "))
        assertFalse(CompetitorRules.canAdd(emptyList(), "x".repeat(61)))
    }
}

class NemotronVariantTest {
    @Test
    fun `variant is inferred from the model id with role fallback`() {
        assertEquals(NemotronVariant.NANO, NemotronVariant.fromModelId("nvidia/NVIDIA-Nemotron-Nano-9B-v2", null))
        assertEquals(NemotronVariant.SUPER, NemotronVariant.fromModelId("nvidia/Llama-3_3-Nemotron-Super-49B", null))
        assertEquals(NemotronVariant.ULTRA, NemotronVariant.fromModelId("nvidia/Nemotron-Ultra-253B", null))
        assertEquals(NemotronVariant.NANO, NemotronVariant.fromModelId("custom", ModelRole.FAST))
        assertEquals(NemotronVariant.SUPER, NemotronVariant.fromModelId(null, ModelRole.REASONING))
        assertEquals(NemotronVariant.UNKNOWN, NemotronVariant.fromModelId(null, null))
    }

    @Test
    fun `sentiment share handles zero total`() {
        assertEquals(0f, SentimentBreakdown.EMPTY.share(com.sift.app.domain.model.Sentiment.POSITIVE))
        assertEquals(0.5f, SentimentBreakdown(1, 0, 1).share(com.sift.app.domain.model.Sentiment.NEGATIVE))
    }
}

class MarkdownBuilderTest {
    private val labels = MarkdownLabels(
        reportTitle = "Sift report: %1\$s",
        sourceLine = "Source: %1\$s",
        countryLine = "Country: %1\$s",
        overviewHeading = "Overview",
        reviewsAnalysed = "Reviews analysed: %1\$d",
        averageRating = "Average rating: %1\$.1f / 5",
        sentimentLine = "Sentiment: %1\$s",
        positive = "positive",
        neutral = "neutral",
        negative = "negative",
        starsColumn = "Stars",
        reviewsColumn = "Reviews",
        categoryColumn = "Category",
        categoryNames = ReviewCategory.entries.associateWith { it.name.lowercase() },
        sourceNames = AnalysisSource.entries.associateWith { it.name },
        themesHeading = "Themes",
        themeStats = "%1\$d reviews · %2\$d%% negative",
        backlogHeading = "Backlog",
        backlogItemHeading = "%1\$d. %2\$s (%3\$s, priority %4\$d, effort %5\$s)",
        typeNames = mapOf(BacklogType.BUG to "Bug", BacklogType.FEATURE to "Feature"),
        themeLine = "Theme: %1\$s",
        whyRanks = "Why:",
        userImpact = "Impact:",
        suggestedFix = "Fix:",
        evidence = "Evidence",
        competitorsHeading = "Competitors",
        strengths = "Strengths",
        weaknesses = "Weaknesses",
        opportunities = "Opportunities",
        sources = "Sources",
        footer = "Generated by Sift",
        ticketPriority = "Priority: %1\$d",
        ticketEffort = "Effort: %1\$s",
        ticketType = "Type: %1\$s"
    )

    private val item = BacklogItem(
        id = 1, rank = 1, title = "Fix sync crash", type = BacklogType.BUG, priorityScore = 92,
        reasoning = "Most severe", userImpact = "All iOS 17 users", suggestedFix = "Guard nil token",
        effort = Effort.M, themeTitle = "Sync crashes", evidenceQuotes = listOf("It crashes\nevery time")
    )

    private fun report() = Report(
        analysis = analysis().copy(
            stats = AnalysisStats.EMPTY.copy(
                totalReviews = 4,
                averageRating = 3.25,
                sentiment = SentimentBreakdown(2, 1, 1),
                categories = mapOf(ReviewCategory.BUG to 3, ReviewCategory.ADS to 0),
                ratingDistribution = listOf(1, 0, 1, 0, 2)
            )
        ),
        themes = listOf(Theme(1, 0, "Sync crashes", "Users lose notes.", 3, 0.67f, listOf("Lost my notes"))),
        backlog = listOf(item),
        competitors = listOf(
            CompetitorInsight(1, "Bear", "Popular", listOf("Fast"), emptyList(), listOf("Cheaper plan"),
                listOf(SourceLink("", "https://bear.app")), ""),
            CompetitorInsight(2, "Broken", "", emptyList(), emptyList(), emptyList(), emptyList(), "failed")
        )
    )

    @Test
    fun `report contains every section with real numbers`() {
        val markdown = MarkdownBuilder(labels).report(report())
        assertTrue(markdown.startsWith("# Sift report: Notes"))
        assertTrue(markdown.contains("- Reviews analysed: 4"))
        assertTrue(markdown.contains("50% positive, 25% neutral, 25% negative"))
        assertTrue(markdown.contains("| 5 | 2 |"))
        assertTrue(markdown.contains("| bug | 3 |"))
        assertFalse(markdown.contains("| ads |"))
        assertTrue(markdown.contains("3 reviews · 67% negative"))
        assertTrue(markdown.contains("### 1. Fix sync crash (Bug, priority 92, effort M)"))
        assertTrue(markdown.contains("> It crashes every time"))
        assertTrue(markdown.contains("- [https://bear.app](https://bear.app)"))
        assertFalse(markdown.contains("Broken"))
    }

    @Test
    fun `ticket has metadata and body`() {
        val ticket = MarkdownBuilder(labels).ticket(item)
        assertTrue(ticket.startsWith("## Fix sync crash"))
        assertTrue(ticket.contains("- Priority: 92"))
        assertTrue(ticket.contains("- Theme: Sync crashes"))
        assertTrue(ticket.contains("**Fix:** Guard nil token"))
        assertEquals(1, Regex("Theme: Sync crashes").findAll(ticket).count())
    }
}
