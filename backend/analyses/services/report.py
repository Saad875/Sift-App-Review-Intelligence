"""Markdown export of a finished analysis."""
from __future__ import annotations

from ..models import Analysis
from .stats import summary_stats

CATEGORY_LABELS = {
    "bug": "Bugs",
    "performance": "Performance",
    "ui_ux": "UI and UX",
    "feature_request": "Feature requests",
    "pricing": "Pricing",
    "ads": "Ads",
    "account": "Account",
    "praise": "Praise",
    "other": "Other",
}


def _percent(part: int, whole: int) -> str:
    return f"{round(100 * part / whole)}%" if whole else "0%"


def build_markdown(analysis: Analysis) -> str:
    """Render the full report: overview, themes, backlog and competitors."""
    stats = summary_stats(analysis)
    total = stats["total_reviews"]
    lines: list[str] = [f"# Sift report: {analysis.app_name}", ""]
    meta = [f"Source: {analysis.get_source_display()}"]
    if analysis.source == Analysis.Source.APPSTORE:
        meta.append(f"Country: {analysis.country.upper()}")
    meta.append(f"Generated: {analysis.created_at:%Y-%m-%d %H:%M} UTC")
    lines += [" · ".join(meta), ""]

    lines += ["## Overview", ""]
    lines.append(f"- Reviews analysed: {total}")
    if stats["average_rating"] is not None:
        lines.append(f"- Average rating: {stats['average_rating']} / 5")
    sentiment = stats["sentiment"]
    classified = stats["classified_reviews"]
    lines.append(
        "- Sentiment: "
        + ", ".join(f"{_percent(sentiment[key], classified)} {key}" for key in ("positive", "neutral", "negative"))
    )
    lines.append("")
    lines += ["| Stars | Reviews |", "|---|---|"]
    for star in range(5, 0, -1):
        lines.append(f"| {star} | {stats['rating_distribution'][str(star)]} |")
    lines.append("")
    top_categories = sorted(stats["categories"].items(), key=lambda kv: -kv[1])
    lines += ["| Category | Reviews |", "|---|---|"]
    for key, count in top_categories:
        if count:
            lines.append(f"| {CATEGORY_LABELS.get(key, key)} | {count} |")
    lines.append("")

    themes = list(analysis.themes.all())
    if themes:
        lines += ["## Themes", ""]
        for theme in themes:
            lines.append(f"### {theme.title}")
            lines.append(
                f"{theme.review_count} reviews · {round(theme.negative_share * 100)}% negative"
            )
            lines += ["", theme.description, ""]
            for text in theme.quotes:
                lines.append(f"> {text}")
                lines.append("")

    backlog = list(analysis.backlog.select_related("theme"))
    if backlog:
        lines += ["## Prioritised backlog", ""]
        for item in backlog:
            lines.append(
                f"### {item.rank}. {item.title} ({item.get_item_type_display()}, priority {item.priority_score}, effort {item.effort})"
            )
            if item.theme:
                lines.append(f"Theme: {item.theme.title}")
            lines += [
                "",
                f"**Why it ranks here:** {item.reasoning}",
                "",
                f"**User impact:** {item.user_impact}",
                "",
                f"**Suggested fix:** {item.suggested_fix}",
                "",
            ]
            for text in item.evidence_quotes:
                lines.append(f"> {text}")
                lines.append("")

    insights = [c for c in analysis.competitor_insights.all() if not c.error]
    if insights:
        lines += ["## Competitors", ""]
        for insight in insights:
            lines.append(f"### {insight.name}")
            if insight.summary:
                lines += ["", insight.summary]
            for heading, values in (
                ("Strengths", insight.strengths),
                ("Weaknesses", insight.weaknesses),
                ("Opportunities for us", insight.opportunities),
            ):
                if values:
                    lines += ["", f"**{heading}**", ""]
                    lines += [f"- {value}" for value in values]
            if insight.sources:
                lines += ["", "**Sources**", ""]
                lines += [f"- [{s.get('title') or s['url']}]({s['url']})" for s in insight.sources]
            lines.append("")

    lines += ["---", "Generated by Sift with NVIDIA Nemotron on Nebius Token Factory."]
    return "\n".join(lines).rstrip() + "\n"
